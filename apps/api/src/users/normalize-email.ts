/**
 * Канонический вид email для хранения и поиска.
 *
 * Живёт в users, потому что это инвариант таблицы User, а не правило одного сценария:
 * колонка — обычный TEXT с регистрозависимым UNIQUE-индексом, поэтому запись и чтение
 * обязаны приводить email к одному виду. Нормализуй только запись — и вход перестанет
 * находить пользователя, который зарегистрировался с заглавными буквами.
 */
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}
