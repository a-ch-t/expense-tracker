import type { User } from './user';

/**
 * Три исхода проверки сессии, а не «пользователь или null».
 *
 * Различать `unauthenticated` и `unavailable` обязательно: proxy пускает на закрытые
 * страницы по сроку жизни токена, и если страница на любой отказ уводит на /login,
 * то при живом по exp токене без сессии (лежит API, пользователя удалили, сменили
 * JWT_SECRET) proxy вернёт обратно — получится бесконечный цикл редиректов.
 */
export type SessionState =
  | { status: 'authenticated'; user: User }
  /** API ответил 401: токена нет, он протух или подделан. */
  | { status: 'unauthenticated' }
  /** Проверить не удалось: API недоступен или ответил 5xx. Про сессию ничего не известно. */
  | { status: 'unavailable' };
