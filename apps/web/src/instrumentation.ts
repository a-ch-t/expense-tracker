/**
 * Подтягивает переменные из корневого `.env` монорепозитория в серверный рантайм.
 *
 * Next сам читает `.env` только рядом с приложением (`apps/web`), а он лежит в корне.
 * Делать это в `next.config.ts` нельзя: конфиг исполняется в отдельном процессе, и
 * `process.env` сервера от него не наследуется — переменные до кода не доходили.
 * `register()` же выполняется в самом серверном процессе до первого запроса.
 */
export async function register() {
  // Edge-рантайм (там работает proxy.ts) переменные из .env не читает и Node-API не умеет.
  // Загрузку выносим в отдельный модуль: файл instrumentation собирается для обоих
  // рантаймов, и обращение к node:-модулям прямо здесь ломало бы Edge-бандл.
  if (process.env['NEXT_RUNTIME'] === 'nodejs') {
    await import('./instrumentation.node');
  }
}
